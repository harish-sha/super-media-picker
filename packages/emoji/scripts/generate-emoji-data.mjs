import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const sourcePath = require.resolve("emojibase-data/en/data.json");
const shortcodesPath =
  require.resolve("emojibase-data/en/shortcodes/emojibase.json");
const records = JSON.parse(await readFile(sourcePath, "utf8"));
const shortcodes = JSON.parse(await readFile(shortcodesPath, "utf8"));
const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(packageRoot, "src/data/emoji-data.generated.ts");
const compactOutputPath = resolve(
  packageRoot,
  "src/data/compact-emoji-data.generated.ts",
);

const compactEmojiIds = new Set([
  "1F44B",
  "1F44D",
  "2764",
  "1F602",
  "1F62E",
  "1F622",
  "1F64F",
  "1F600",
  "1F44E",
  "1F621",
]);

const categories = new Map([
  [0, "Smileys & Emotion"],
  [1, "People & Body"],
  [3, "Animals & Nature"],
  [4, "Food & Drink"],
  [5, "Travel & Places"],
  [6, "Activities"],
  [7, "Objects"],
  [8, "Symbols"],
  [9, "Flags"],
]);

const aliasesByLabel = {
  "beaming face with smiling eyes": ["happy", "grin"],
  "face with tears of joy": ["laugh", "happy", "lol"],
  fire: ["lit", "flame"],
  "party popper": ["celebrate", "tada"],
  "red heart": ["love"],
  rocket: ["launch", "ship"],
  "thumbs up": ["like", "+1"],
};

const skinTones = new Map([
  [1, "light"],
  [2, "medium-light"],
  [3, "medium"],
  [4, "medium-dark"],
  [5, "dark"],
]);

const compact = records
  .filter(
    (record) =>
      categories.has(record.group) && typeof record.emoji === "string",
  )
  .map((record) => {
    const label = String(record.label);
    const aliases = new Set([
      ...(Array.isArray(record.tags) ? record.tags : []),
      ...(record.emoticon ? [record.emoticon] : []),
      ...(Array.isArray(shortcodes[record.hexcode])
        ? shortcodes[record.hexcode]
        : shortcodes[record.hexcode]
          ? [shortcodes[record.hexcode]]
          : []),
      ...(aliasesByLabel[label] ?? []),
    ]);
    aliases.delete(label);
    return {
      id: String(record.hexcode).toLowerCase(),
      value: record.emoji,
      name: label,
      category: categories.get(record.group),
      aliases: [...aliases].map(String).sort(),
      variants: (Array.isArray(record.skins) ? record.skins : [])
        .filter(
          (variant) =>
            skinTones.has(variant.tone) && typeof variant.emoji === "string",
        )
        .map((variant) => ({
          id: String(variant.hexcode).toLowerCase(),
          value: variant.emoji,
          kind: "skin-tone",
          skinTone: skinTones.get(variant.tone),
        })),
    };
  });

const banner = `// Generated by scripts/generate-emoji-data.mjs from Emojibase. Do not edit.\nimport type { EmojiRecord } from "../types";\n\n`;
const serializedRecords = compact
  .map((record) => `${JSON.stringify(record)} as EmojiRecord`)
  .join(",");
const compactRecords = compact.filter((record) =>
  compactEmojiIds.has(record.id.toUpperCase()),
);
const serializedCompactRecords = compactRecords
  .map((record) => `${JSON.stringify(record)} as EmojiRecord`)
  .join(",");
await writeFile(
  outputPath,
  `${banner}export const emojiData: readonly EmojiRecord[] = [${serializedRecords}];\n`,
  "utf8",
);
await writeFile(
  compactOutputPath,
  `${banner}export const compactEmojiData: readonly EmojiRecord[] = [${serializedCompactRecords}];\n`,
  "utf8",
);

process.stdout.write(
  `Generated ${compact.length} emoji records and ${compactRecords.length} compact records.\n`,
);
